// 12. Program to demonstrate relational operators.

#include <iostream>
using namespace std;

int main() {
    int a = 10, b = 20;

    cout << "a="<<a<< endl;
    cout << "b="<<b<< endl;

    cout <<"Relational operations"<< endl;

    cout << "a == b : " << (a == b) << endl;
    cout << "a != b : " << (a != b) << endl;
    cout << "a > b  : " << (a > b) << endl;
    cout << "a < b  : " << (a < b) << endl;
    cout << "a >= b : " << (a >= b) << endl;
    cout << "a <= b : " << (a <= b) << endl;

    return 0;
}
